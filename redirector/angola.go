var aoPrefixes []netip.Prefix

func init() {
	aoPrefixes = aoPrefixes[:0]
	for _, c := range angolaCIDRs {
		if p, err := netip.ParsePrefix(c); err == nil {
			aoPrefixes = append(aoPrefixes, p)
		}
	}
}

func IsAngolaIP(ip string) bool {
	addr, err := netip.ParseAddr(ip)
	if err != nil || !addr.Is4() {
		return false
	}
	for _, p := range aoPrefixes {
		if p.Contains(addr) {
			return true
		}
	}
	return false
}
